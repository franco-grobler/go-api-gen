package gen

import (
	"bytes"
	"fmt"
	"path/filepath"

	"github.com/franco-grobler/go-api-gen/internal/config"
	"github.com/franco-grobler/go-api-gen/internal/naming"
	"github.com/franco-grobler/go-api-gen/internal/spec"
	"github.com/franco-grobler/go-api-gen/internal/workspace"
)

// UnifiedPath resolves where the unified spec is written. An override from
// the command line wins over the configured path.
func (g *Generator) UnifiedPath(override string) (string, error) {
	if override != "" {
		return filepath.Abs(override)
	}
	if cfg := g.ws.Config.Unified; cfg != nil && cfg.AbsTo != "" {
		return cfg.AbsTo, nil
	}
	return "", fmt.Errorf("no output path for the unified spec; set " +
		"unified.to in the config or pass --output")
}

// Unified renders every service's operations into one self-contained OpenAPI
// document.
func (g *Generator) Unified() ([]byte, error) {
	cfg := g.ws.Config.Unified
	if cfg == nil {
		cfg = &config.UnifiedConfig{Title: "Unified API", Version: "0.0.0"}
	}

	svcs := g.unifiedServices(cfg)
	if len(svcs) == 0 {
		return nil, fmt.Errorf("no services contribute to the unified spec")
	}

	tags := g.unifiedTags(svcs, cfg.Tags())
	sources := make([]spec.UnifySource, 0, len(svcs))
	for _, p := range svcs {
		src := spec.UnifySource{Doc: p.Doc}
		if cfg.Tags() {
			src.Tag = tags[p]
			src.TagDescription = p.Doc.Info.Description
		}
		sources = append(sources, src)
	}

	comps, err := g.unifiedComponents(svcs)
	if err != nil {
		return nil, err
	}

	servers := make([]spec.Server, len(cfg.Servers))
	for i, s := range cfg.Servers {
		servers[i] = spec.Server{URL: s.URL, Description: s.Description}
	}

	node, err := g.ws.Loader.Unify(&spec.UnifyOptions{
		Info: spec.UnifyInfo{
			Title:       cfg.Title,
			Version:     cfg.Version,
			Description: cfg.Description,
		},
		Servers:    servers,
		Sources:    sources,
		Components: comps,
	})
	if err != nil {
		return nil, err
	}
	body, err := spec.MarshalBundle(node)
	if err != nil {
		return nil, err
	}

	var out bytes.Buffer
	out.WriteString("# Code generated by go-api-gen. DO NOT EDIT.\n")
	out.WriteString("# Unified specification stitched from:\n")
	for _, p := range svcs {
		fmt.Fprintf(&out, "#   %s\n", g.relSource(p.Cfg.Spec))
	}
	out.Write(body)
	return out.Bytes(), nil
}

// unifiedTags names each contributing service for the merged document's tag
// list.
//
// The Go package name is the wrong source: several services conventionally
// generate into internal/api, so every operation would carry the same tag and
// the merged document would be no easier to navigate than an untagged one. The
// service's own info.title is what a reader recognises, with its configured
// name as a fallback and as the tie-breaker when two titles match.
func (g *Generator) unifiedTags(
	svcs []*workspace.Service,
	enabled bool,
) map[*workspace.Service]string {
	out := map[*workspace.Service]string{}
	if !enabled {
		return out
	}

	count := map[string]int{}
	for _, p := range svcs {
		count[preferredTag(p)]++
	}
	taken := map[string]bool{}
	for _, p := range svcs {
		name := preferredTag(p)
		if count[name] > 1 {
			name = p.Name
		}
		for i := 2; taken[name]; i++ {
			name = fmt.Sprintf("%s%d", preferredTag(p), i)
		}
		taken[name] = true
		out[p] = name
	}
	return out
}

func preferredTag(p *workspace.Service) string {
	if t := p.Doc.Info.Title; t != "" {
		return t
	}
	return p.Name
}

// unifiedServices returns the services contributing to the unified document,
// in name order.
func (g *Generator) unifiedServices(
	cfg *config.UnifiedConfig,
) []*workspace.Service {
	var out []*workspace.Service
	for _, p := range g.ws.Services {
		if cfg.Excludes(p.Name) {
			continue
		}
		out = append(out, p)
	}
	return out
}

// unifiedComponents names every schema reachable from any contributing
// service.
//
// A name that is unique within one Go package can still collide here, because
// the unified document pools schemas from every service at once. The Go name
// is preferred so the document and the code agree, and a collision is resolved
// by qualifying with the owning package.
func (g *Generator) unifiedComponents(svcs []*workspace.Service) (
	[]spec.BundleComponent,
	error,
) {
	taken := map[string]*spec.Schema{}
	seen := map[*spec.Schema]bool{}
	var out []spec.BundleComponent

	for _, svc := range svcs {
		for _, s := range svc.Reachable {
			if seen[s] {
				continue
			}
			seen[s] = true

			name := g.ws.GoName(s)
			owner := g.ws.Owner(s)
			if prev, dup := taken[name]; dup && prev != s {
				name = naming.Exported(owner.GoPackage()) + name
			}
			if prev, dup := taken[name]; dup && prev != s {
				return nil, fmt.Errorf("%s: cannot name component %q uniquely "+
					"in the unified spec; set x-go-name on one of the "+
					"colliding schemas", s.Loc, name)
			}
			taken[name] = s
			out = append(out, spec.BundleComponent{Schema: s, Name: name})
		}
	}
	return out, nil
}
